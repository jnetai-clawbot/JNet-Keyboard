    /** Registers every extra trigger word with the emoji it belongs to. */
    static void apply() {
        for (String line : TABLE.split("\n")) {
            String entry = line.trim();
            if (entry.isEmpty() || entry.startsWith("//")) continue;
            int eq = entry.indexOf('=');
            if (eq <= 0) continue;
            String[] words = entry.substring(0, eq).split(",");
            String[] targets = splitEmoji(entry.substring(eq + 1));
            if (targets.length == 0) continue;
            for (String target : targets) {
                for (String word : words) {
                    String w = word.trim();
                    if (!w.isEmpty()) EmojiDatabase.addSynonyms(target, w);
                }
            }
        }
    }

    /** Splits a run of emoji, keeping ZWJ sequences and variation selectors together. */
    private static String[] splitEmoji(String s) {
        List<String> out = new ArrayList<>();
        int i = 0;
        while (i < s.length()) {
            int cp = s.codePointAt(i);
            int start = i;
            i += Character.charCount(cp);
            boolean joiner = false;
            while (i < s.length()) {
                int c = s.codePointAt(i);
                if (c == 0x200D || c == 0xFE0F || c == 0x20E3) {
                    joiner = true;
                    i += Character.charCount(c);
                } else if (c >= 0x1F3FB && c <= 0x1F3FF) {
                    i += Character.charCount(c);
                } else if (joiner && isModifierBase(c)) {
                    i += Character.charCount(c);
                } else {
                    break;
                }
            }
            out.add(s.substring(start, i));
        }
        return out.toArray(new String[0]);
    }

    /** Skin-tone / keycap bases that may follow a ZWJ or variation selector. */
    private static boolean isModifierBase(int cp) {
        return (cp >= 0x1F466 && cp <= 0x1F487) || cp == 0x2695 || cp == 0x2696
                || (cp >= 0x1F918 && cp <= 0x1F97A) || (cp >= 0x1FA70 && cp <= 0x1FAFF)
                || (cp >= 0x1F393 && cp <= 0x1F3A0) || cp == 0x2640 || cp == 0x2642
                || cp == 0x2695 || cp == 0x2696 || cp == 0x2708 || cp == 0x2764
                || cp == 0x1F004 || cp == 0x1F0CF;
    }
